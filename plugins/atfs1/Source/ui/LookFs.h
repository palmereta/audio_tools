// Texto en matriz de puntos: cada carácter ocupa 6×8 celdas de `dot` px. Con `ghost` dibuja también los
// puntos apagados (como un LCD de caracteres real).
inline void dotText (juce::Graphics& g, const juce::String& s, float x, float y, float dot, juce::Colour ink, bool ghost = true, int maxChars = 999)
{
    const float d = dot * 0.84f;
    for (int ci = 0; ci < std::min (s.length(), maxChars); ++ci)
    {
        const juce::juce_wchar ch = s[ci];
        const uint8_t* gl = glyph5x7 (ch < 127 ? (char) ch : '?');
        for (int c = 0; c < 5; ++c)
            for (int r = 0; r < 7; ++r)
            {
                const bool on = (gl[c] >> r) & 1;
                if (! on && ! ghost) continue;
                g.setColour (on ? ink : ink.withAlpha (0.07f));
                g.fillRect (x + (float) (ci * 6 + c) * dot, y + (float) r * dot, d, d);
            }
    }
}

// Sección con título (sin mayúsculas forzadas: el título es la información, no un adorno).
inline juce::Rectangle<int> section (juce::Graphics& g, juce::Rectangle<int> r, const juce::String& title)
{
    g.setColour (col::surface);
    g.fillRoundedRectangle (r.toFloat(), 6.0f);
    g.setColour (col::border);
    g.drawRoundedRectangle (r.toFloat().reduced (0.5f), 6.0f, 1.0f);
    if (title.isNotEmpty())
    {
        g.setColour (col::dim);
        g.setFont (font (12.5f, true));
        g.drawText (title, r.getX() + 12, r.getY() + 6, r.getWidth() - 24, 18, juce::Justification::centredLeft);
        return r.withTrimmedTop (28).reduced (10, 6);
    }
    return r.reduced (10);
}

