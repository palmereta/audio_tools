inline juce::Font font (float h, bool bold = false) { return juce::FontOptions (h, bold ? juce::Font::bold : juce::Font::plain); }

// Panel de LCD: cristal con la luz de fondo, un leve viñeteado y el marco negro.
inline void lcdPanel (juce::Graphics& g, juce::Rectangle<float> r, float frame = 3.0f)
{
    g.setColour (juce::Colour (0xff07090b));
    g.fillRoundedRectangle (r, 4.0f);
    const auto in = r.reduced (frame);
    juce::ColourGradient gr (col::lcdHi, in.getCentreX(), in.getCentreY(), col::lcdLo, in.getX(), in.getY(), true);
    g.setGradientFill (gr);
    g.fillRoundedRectangle (in, 2.0f);
    g.setColour (juce::Colours::black.withAlpha (0.18f));
    g.drawRoundedRectangle (in.reduced (0.5f), 2.0f, 1.0f);
}

